begin;

create table if not exists public.obras (
  id bigint generated by default as identity primary key,
  titulo text not null,
  autor text not null,
  duracion_minutos integer not null check (duracion_minutos > 0),
  sinopsis text,
  img text,
  video_url text,
  activa boolean not null default true,
  visible_galeria boolean not null default false,
  anio integer,
  asistencia integer check (asistencia is null or asistencia >= 0),
  resena text,
  created_at timestamptz not null default now()
);

create table if not exists public.salas (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  capacidad integer not null check (capacidad > 0),
  activa boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.funciones (
  id text primary key,
  obra_id bigint not null references public.obras(id) on delete restrict,
  sala_id bigint not null references public.salas(id) on delete restrict,
  inicio timestamp without time zone not null,
  estado text not null default 'programada'
    check (estado in ('programada', 'cancelada', 'finalizada')),
  created_at timestamptz not null default now(),
  unique (sala_id, inicio)
);

create index if not exists funciones_obra_inicio_idx
  on public.funciones (obra_id, inicio);

create table if not exists public.butacas (
  id bigint generated by default as identity primary key,
  sala_id bigint not null references public.salas(id) on delete cascade,
  fila text not null check (fila ~ '^[A-Z]$'),
  numero smallint not null check (numero > 0),
  activa boolean not null default true,
  unique (sala_id, fila, numero)
);

create table if not exists public.ordenes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  estado text not null default 'confirmada'
    check (estado in ('pendiente', 'confirmada', 'cancelada')),
  total numeric(10, 2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists ordenes_user_created_idx
  on public.ordenes (user_id, created_at desc);

create table if not exists public.talleres (
  id bigint generated by default as identity primary key,
  titulo text not null unique,
  horario text not null,
  cupos integer not null check (cupos >= 0),
  descripcion text not null,
  img text,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.inscripciones_talleres (
  id uuid primary key default gen_random_uuid(),
  taller_id bigint not null references public.talleres(id) on delete restrict,
  user_id uuid references auth.users(id) on delete set null,
  nombre text not null,
  email text not null,
  experiencia text not null
    check (experiencia in ('Ninguna', 'Básica', 'Intermedia', 'Avanzada')),
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'aceptada', 'rechazada', 'cancelada')),
  created_at timestamptz not null default now(),
  unique (taller_id, email)
);

create table if not exists public.convocatorias (
  id bigint generated by default as identity primary key,
  titulo text not null,
  descripcion text not null,
  requisitos text,
  abre_en timestamptz,
  cierra_en timestamptz,
  estado text not null default 'borrador'
    check (estado in ('borrador', 'publicada', 'cerrada')),
  created_at timestamptz not null default now(),
  check (cierra_en is null or abre_en is null or cierra_en > abre_en)
);

create table if not exists public.postulaciones (
  id uuid primary key default gen_random_uuid(),
  convocatoria_id bigint not null references public.convocatorias(id) on delete restrict,
  user_id uuid references auth.users(id) on delete set null,
  nombre text not null,
  email text not null,
  presentacion text,
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'en_revision', 'aceptada', 'rechazada')),
  created_at timestamptz not null default now(),
  unique (convocatoria_id, email)
);

alter table public.reservas
  add column if not exists orden_id uuid;

