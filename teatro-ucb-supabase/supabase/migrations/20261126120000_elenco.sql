begin;

-- Integrantes del taller, agrupados por paralelo.
create table if not exists public.miembros_elenco (
  id bigint generated by default as identity primary key,
  nombre text not null check (char_length(btrim(nombre)) between 2 and 120),
  categoria text not null check (categoria in ('oficial', 'juveniles', 'aspirantes')),
  foto_url text,
  foto_path text,
  created_at timestamptz not null default now()
);

create index if not exists miembros_elenco_categoria_nombre_idx
  on public.miembros_elenco (categoria, nombre);

-- Quién participa en cada obra y con qué personaje o rol.
create table if not exists public.elenco_obras (
  obra_id bigint not null references public.obras(id) on delete cascade,
  miembro_id bigint not null references public.miembros_elenco(id) on delete cascade,
  personaje text not null check (char_length(btrim(personaje)) between 1 and 120),
  orden smallint not null default 0,
  created_at timestamptz not null default now(),
  primary key (obra_id, miembro_id)
);

create index if not exists elenco_obras_miembro_idx
  on public.elenco_obras (miembro_id);

alter table public.miembros_elenco enable row level security;
alter table public.elenco_obras enable row level security;

drop policy if exists "Elenco público" on public.miembros_elenco;
create policy "Elenco público"
  on public.miembros_elenco for select to anon, authenticated
  using (true);

drop policy if exists "Administrar elenco" on public.miembros_elenco;
create policy "Administrar elenco"
  on public.miembros_elenco for all to authenticated
  using (public.es_administrador())
  with check (public.es_administrador());

drop policy if exists "Elenco de obras público" on public.elenco_obras;
create policy "Elenco de obras público"
  on public.elenco_obras for select to anon, authenticated
  using (true);

drop policy if exists "Administrar elenco de obras" on public.elenco_obras;
create policy "Administrar elenco de obras"
  on public.elenco_obras for all to authenticated
  using (public.es_administrador())
  with check (public.es_administrador());

grant select on public.miembros_elenco, public.elenco_obras to anon, authenticated;
grant insert, update, delete on public.miembros_elenco, public.elenco_obras to authenticated;

-- Fotos de perfil: lectura pública, solo los administradores pueden subir o borrar.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('elenco', 'elenco', true, 2097152, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Administradores suben fotos del elenco" on storage.objects;
create policy "Administradores suben fotos del elenco"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'elenco' and public.es_administrador());

drop policy if exists "Administradores actualizan fotos del elenco" on storage.objects;
create policy "Administradores actualizan fotos del elenco"
  on storage.objects for update to authenticated
  using (bucket_id = 'elenco' and public.es_administrador())
  with check (bucket_id = 'elenco' and public.es_administrador());

drop policy if exists "Administradores borran fotos del elenco" on storage.objects;
create policy "Administradores borran fotos del elenco"
  on storage.objects for delete to authenticated
  using (bucket_id = 'elenco' and public.es_administrador());

commit;
